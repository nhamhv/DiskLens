//! What a scanned path is (category) and whether deleting it is safe (safety).
//!
//! "Safe" is an allowlist: a path only gets it by matching a known-junk rule. Everything
//! else is "review" (the user's own files), "risky" (system and app data) or "unknown".
//!
//! Rules apply from the root down and the shallowest match wins. Once a folder matches a
//! `fixed` rule, everything inside it shares its class, so `/System/Library/Caches` stays
//! risky and a `node_modules` inside `~/Library/Application Support` is never "safe".
//! `classify` (one path) and `summarize` (a whole subtree) both go through `step`, so they
//! always agree.

use crate::scanner::Node;
use serde::Serialize;
use std::collections::HashMap;
use std::path::{Path, PathBuf};

#[derive(Serialize, Clone, Copy, PartialEq, Eq, Hash, Debug)]
#[serde(rename_all = "camelCase")]
pub enum Category {
    System,
    Applications,
    Developer,
    Caches,
    Logs,
    Trash,
    AppData,
    Containers,
    Mail,
    Media,
    Documents,
    Downloads,
    Other,
}

#[derive(Serialize, Clone, Copy, PartialEq, Eq, Hash, Debug)]
#[serde(rename_all = "lowercase")]
pub enum Safety {
    /// Regenerated on its own: caches, logs, Trash, build junk.
    Safe,
    /// The user's own files: theirs to decide.
    Review,
    /// System or app data: deleting can break apps or the OS.
    Risky,
    Unknown,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Class {
    pub category: Category,
    pub safety: Safety,
    /// Everything inside shares this class; no rule below it is checked.
    pub fixed: bool,
}

const fn class(category: Category, safety: Safety, fixed: bool) -> Class {
    Class { category, safety, fixed }
}

use Category::*;
use Safety::*;

const ROOT: Class = class(Other, Unknown, false);

/// Code bundles: sized as one item, their contents aren't kept (an app holds thousands
/// of files nobody browses). Opening one rescans it.
const BUNDLES: &[&str] = &[
    "app", "appex", "framework", "bundle", "plugin", "kext", "xpc", "prefpane", "qlgenerator", "mdimporter",
    "saver", "component", "vst", "vst3",
];

/// Libraries managed by an app; editing them by hand corrupts the library.
const MEDIA_LIBRARIES: &[&str] = &["photoslibrary", "photolibrary", "musiclibrary", "tvlibrary", "imovielibrary", "fcpbundle"];

/// Regenerated by the tool that made them, wherever they are.
const DEV_JUNK: &[&str] = &[
    "node_modules", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", "deriveddata", ".parcel-cache", ".turbo",
];

/// Toolchains and tool data in the home folder: developer stuff, but not automatically junk.
const DEV_HOME: &[&str] = &[
    ".cargo", ".rustup", ".nvm", ".npm", ".gradle", ".android", ".m2", ".pub-cache", ".vscode", ".cursor", ".docker",
    ".bun", ".deno", "go", ".pyenv", ".rbenv", ".conda", "miniconda3", "anaconda3", ".claude", ".codex", ".gemini",
    ".ollama", "library/developer",
];

/// Safe folders the cleanup list shows item by item, since the folder itself must stay.
const CONTAINERS: &[&str] = &["library/caches", "library/logs", ".cache"];

const MEDIA_EXT: &[&str] = &[
    "mp4", "mov", "m4v", "avi", "mkv", "webm", "mp3", "wav", "aac", "flac", "m4a", "aiff", "jpg", "jpeg", "png", "gif",
    "heic", "tiff", "psd", "cr2", "nef", "dng",
];
const DOC_EXT: &[&str] = &["pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx", "key", "pages", "numbers", "txt", "md"];

fn ext(name: &str) -> Option<&str> {
    let (stem, e) = name.rsplit_once('.')?;
    (!stem.is_empty()).then_some(e)
}

/// `name` is a code bundle whose contents the scanner drops.
pub fn is_bundle(name: &str) -> bool {
    ext(name).is_some_and(|e| BUNDLES.iter().any(|b| e.eq_ignore_ascii_case(b)))
}

fn lower(p: &Path) -> String {
    p.to_string_lossy().to_lowercase()
}

pub struct Classifier {
    /// Lowercase, as macOS volumes are case-insensitive. (Linux paths are matched the same
    /// way; no two rules differ only by case.)
    home: String,
}

impl Classifier {
    pub fn new(home: &Path) -> Self {
        Self { home: lower(home).trim_end_matches('/').to_string() }
    }

    pub fn from_env() -> Self {
        Self::new(&std::env::var_os("HOME").map(PathBuf::from).unwrap_or_default())
    }

    /// The class of `path`, applying the rules to each ancestor from the root down.
    pub fn classify(&self, path: &Path, is_dir: bool) -> Class {
        let chain: Vec<&Path> = path.ancestors().collect();
        let mut cls = ROOT;
        for (i, p) in chain.iter().rev().enumerate() {
            cls = self.step(cls, p, is_dir || i + 1 < chain.len());
            if cls.fixed {
                break;
            }
        }
        cls
    }

    /// The class of `path` given its parent's.
    pub fn step(&self, parent: Class, path: &Path, is_dir: bool) -> Class {
        if parent.fixed {
            return parent;
        }
        let name = path.file_name().map(|n| n.to_string_lossy().to_lowercase()).unwrap_or_default();
        if !is_dir {
            return by_ext(&name).unwrap_or(parent);
        }
        self.rule(&lower(path), &name).unwrap_or(parent)
    }

    fn home_rel<'a>(&self, p: &'a str) -> Option<&'a str> {
        if self.home.is_empty() {
            return None;
        }
        p.strip_prefix(self.home.as_str())?.strip_prefix('/')
    }

    /// The rule for exactly this folder, if any. Ancestors were already checked.
    fn rule(&self, p: &str, name: &str) -> Option<Class> {
        // 1. System first, so nothing in it can read as safe. /usr/local is Homebrew's.
        let usr_local = p == "/usr/local" || p.starts_with("/usr/local/");
        if matches!(p, "/system" | "/bin" | "/sbin" | "/private" | "/cores" | "/var" | "/etc" | "/tmp" | "/dev" | "/library")
            || matches!(p, "/boot" | "/lib" | "/lib32" | "/lib64" | "/libx32" | "/proc" | "/sys" | "/run" | "/snap" | "/root" | "/srv")
            || (p.starts_with("/usr/") && !usr_local)
        {
            return Some(class(System, Risky, true));
        }
        match p {
            "/usr" => return Some(class(System, Risky, false)),
            "/usr/local" | "/opt" => return Some(class(Developer, Review, false)),
            "/applications" => return Some(class(Applications, Review, false)),
            _ => {}
        }

        // 2. Safe: regenerable junk.
        let rel = self.home_rel(p);
        match rel {
            Some(".trash" | ".local/share/trash") => return Some(class(Trash, Safe, true)),
            Some("library/caches" | ".cache") => return Some(class(Caches, Safe, true)),
            Some("library/logs") => return Some(class(Logs, Safe, true)),
            Some(
                ".npm/_cacache"
                | ".gradle/caches"
                | "library/developer/coresimulator/caches"
                | "library/developer/xcode/ios devicesupport"
                | "library/developer/xcode/watchos devicesupport"
                | "library/developer/xcode/tvos devicesupport",
            ) => return Some(class(Developer, Safe, true)),
            _ => {}
        }
        if name == ".trashes" {
            return Some(class(Trash, Safe, true));
        }
        if DEV_JUNK.contains(&name) {
            // `lib/node_modules` holds globally installed tools (npm -g, nvm), not a project's packages.
            let global = name == "node_modules" && p.ends_with("/lib/node_modules");
            return Some(class(Developer, if global { Review } else { Safe }, true));
        }

        // 3. Risky: data that apps and the OS rely on.
        match rel {
            Some("library/mail" | ".thunderbird") => return Some(class(Mail, Risky, true)),
            // Linux: Flatpak and Snap app data.
            Some(".var/app" | "snap") => return Some(class(Containers, Risky, true)),
            Some(".config" | ".mozilla" | ".ssh" | ".gnupg" | ".pki") => return Some(class(AppData, Risky, true)),
            // Each app's folder in `~/.local/share` is fixed, not the folder itself, so the
            // Trash inside it can still be safe.
            Some(".local/share") => return Some(class(AppData, Risky, false)),
            Some(r) if r.strip_prefix(".local/share/").is_some_and(|x| !x.contains('/')) => {
                return Some(class(AppData, Risky, true))
            }
            Some("library/containers" | "library/group containers") => return Some(class(Containers, Risky, true)),
            Some(
                "library/application support"
                | "library/preferences"
                | "library/keychains"
                | "library/messages"
                | "library/cloudstorage"
                | "library/mobile documents",
            ) => return Some(class(AppData, Risky, true)),
            _ => {}
        }
        if name == ".git" {
            return Some(class(Developer, Risky, true));
        }
        if let Some(e) = ext(name) {
            if MEDIA_LIBRARIES.contains(&e) {
                return Some(class(Media, Risky, true));
            }
            if e == "app" {
                return Some(class(Applications, Review, true));
            }
        }

        // 4. Review: the user's own folders. Not fixed, so junk inside them is still found.
        match rel {
            Some("library") => return Some(class(AppData, Review, false)),
            Some("downloads") => return Some(class(Downloads, Review, false)),
            Some("documents" | "desktop") => return Some(class(Documents, Review, false)),
            Some("pictures" | "movies" | "music" | "videos") => return Some(class(Media, Review, false)),
            Some(".local") => return Some(class(AppData, Review, false)),
            Some("applications") => return Some(class(Applications, Review, false)),
            Some(r) if DEV_HOME.contains(&r) => return Some(class(Developer, Review, false)),
            _ => {}
        }
        (p == self.home).then_some(class(Other, Review, false))
    }

    /// A safe folder that must itself stay; the cleanup list shows its items instead.
    fn is_container(&self, path: &Path) -> bool {
        self.home_rel(&lower(path)).is_some_and(|r| CONTAINERS.contains(&r))
    }
}

fn by_ext(name: &str) -> Option<Class> {
    let e = ext(name)?;
    if MEDIA_EXT.contains(&e) {
        Some(class(Media, Review, false))
    } else if DOC_EXT.contains(&e) {
        Some(class(Documents, Review, false))
    } else {
        None
    }
}

/// Totals for a subtree, plus the safe items in it.
#[derive(Default)]
pub struct Tally {
    pub categories: HashMap<Category, u64>,
    pub safety: HashMap<Safety, u64>,
    /// Every safe item at the shallowest level that can be deleted: (path, is_dir, size, items).
    pub safe: Vec<(PathBuf, bool, u64, usize)>,
}

impl Tally {
    fn add(&mut self, cls: Class, size: u64) {
        if size > 0 {
            *self.categories.entry(cls.category).or_default() += size;
            *self.safety.entry(cls.safety).or_default() += size;
        }
    }

    fn push_safe(&mut self, path: PathBuf, n: &Node) {
        self.safe.push((path, n.is_dir, n.size, n.children.len()));
    }
}

impl Classifier {
    /// Adds `node` (at `path`, whose parent has class `parent`) to `tally`. A fixed class
    /// covers its whole subtree, so only the unclassified parts are walked.
    pub fn summarize(&self, node: &Node, path: &Path, parent: Class, tally: &mut Tally) {
        let cls = self.step(parent, path, node.is_dir);
        if cls.fixed || !node.is_dir {
            tally.add(cls, node.size);
            // The Trash is emptied from the start screen; moving it to the Trash makes no sense.
            if cls.safety == Safe && cls.category != Trash {
                // `parent` is only fixed for the folder `summarize` started in.
                if self.is_container(path) || parent.fixed {
                    node.children.iter().for_each(|c| tally.push_safe(path.join(&c.name), c));
                } else {
                    tally.push_safe(path.to_path_buf(), node);
                }
            }
            return;
        }
        let children: u64 = node.children.iter().map(|c| c.size).sum();
        tally.add(cls, node.size.saturating_sub(children));
        for c in &node.children {
            self.summarize(c, &path.join(&c.name), cls, tally);
        }
    }

    /// The class of `path`'s parent, the starting point for `summarize`.
    pub fn parent_class(&self, path: &Path) -> Class {
        path.parent().map_or(ROOT, |p| self.classify(p, true))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn c() -> Classifier {
        Classifier::new(Path::new("/Users/me"))
    }

    /// Category and safety of a folder.
    fn of(p: &str) -> (Category, Safety) {
        let cls = c().classify(Path::new(p), true);
        (cls.category, cls.safety)
    }

    #[test]
    fn system_wins_over_junk_rules() {
        assert_eq!(c().classify(Path::new("/System/Library/Caches"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/private/var/log/x.log"), false).safety, Risky);
        assert_eq!(c().classify(Path::new("/Library/Caches/node_modules"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/usr/bin"), true).category, System);
        assert_eq!(c().classify(Path::new("/usr/local/lib"), true).category, Developer);
    }

    #[test]
    fn safe_is_an_allowlist() {
        assert_eq!(of("/Users/me/Library/Caches/com.foo"), (Caches, Safe));
        assert_eq!(of("/Users/me/Library/Logs"), (Logs, Safe));
        assert_eq!(of("/Users/me/.Trash"), (Trash, Safe));
        assert_eq!(of("/Users/me/repos/app/node_modules"), (Developer, Safe));
        assert_eq!(c().classify(Path::new("/Users/me/Library/Developer/Xcode/DerivedData"), true).safety, Safe);
        // Names that are often build output are not safe on their own.
        for p in ["/Users/me/repos/app/build", "/Users/me/repos/app/target", "/Users/me/Documents/out", "/Users/me/x/Logs"] {
            assert_ne!(c().classify(Path::new(p), true).safety, Safe, "{p}");
        }
        // Global npm packages, and app data that happens to contain junk names.
        assert_eq!(c().classify(Path::new("/usr/local/lib/node_modules"), true).safety, Review);
        assert_eq!(c().classify(Path::new("/Users/me/Library/Application Support/X/node_modules"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/Users/me/Library/Containers/x/Data/Library/Caches"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/Users/me/.gradle"), true).safety, Review);
    }

    #[test]
    fn user_folders_and_files() {
        assert_eq!(of("/Users/me/Downloads/stuff"), (Downloads, Review));
        assert_eq!(c().classify(Path::new("/Users/me/Downloads/a.mp4"), false).category, Media);
        assert_eq!(c().classify(Path::new("/Users/me/repos/x/.git"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/Users/me/Pictures/P.photoslibrary"), true).safety, Risky);
        assert_eq!(c().classify(Path::new("/Applications/Foo.app"), true).category, Applications);
        assert_eq!(c().classify(Path::new("/Users/me/LIBRARY/CACHES"), true).safety, Safe, "case-insensitive");
        assert_eq!(of("/Volumes/ext/stuff"), (Other, Unknown));
        assert_eq!(of("/Users/me/stuff"), (Other, Review));
    }

    #[test]
    fn linux_paths() {
        let l = Classifier::new(Path::new("/home/me"));
        let of = |p: &str| {
            let k = l.classify(Path::new(p), true);
            (k.category, k.safety)
        };
        assert_eq!(of("/home/me/.cache/pip"), (Caches, Safe));
        assert_eq!(of("/home/me/.local/share/Trash"), (Trash, Safe));
        assert_eq!(of("/home/me/.local/share/Steam/node_modules"), (AppData, Risky));
        assert_eq!(of("/home/me/.config/Code/Cache"), (AppData, Risky));
        assert_eq!(of("/home/me/.var/app/org.x/cache"), (Containers, Risky));
        assert_eq!(of("/home/me/Videos/trip"), (Media, Review));
        assert_eq!(of("/boot/grub"), (System, Risky));
        assert_eq!(of("/var/cache/apt"), (System, Risky));
    }

    #[test]
    fn bundles() {
        assert!(is_bundle("Xcode.app") && is_bundle("Foo.FRAMEWORK"));
        assert!(!is_bundle(".app") && !is_bundle("photos.photoslibrary"));
    }

    #[test]
    fn summarize_agrees_with_classify_and_lists_safe_items() {
        let leaf = |name: &str, size| Node { name: name.into(), size, is_dir: false, modified: 0, children: vec![] };
        let dir = |name: &str, children: Vec<Node>| Node {
            name: name.into(),
            size: children.iter().map(|c| c.size).sum(),
            is_dir: true,
            modified: 0,
            children,
        };
        let home = dir(
            "me",
            vec![
                dir("Library", vec![dir("Caches", vec![dir("a", vec![leaf("x", 10)]), leaf("b", 5)])]),
                dir("repos", vec![dir("p", vec![dir("node_modules", vec![leaf("m", 7)]), leaf("v.mp4", 3)])]),
                dir(".Trash", vec![leaf("old", 100)]),
            ],
        );
        let cl = c();
        let root = Path::new("/Users/me");
        let mut t = Tally::default();
        cl.summarize(&home, root, cl.parent_class(root), &mut t);
        assert_eq!(t.safety[&Safe], 10 + 5 + 7 + 100);
        assert_eq!(t.categories[&Media], 3);
        let mut safe: Vec<_> = t.safe.iter().map(|s| s.0.to_string_lossy().into_owned()).collect();
        safe.sort();
        assert_eq!(
            safe,
            ["/Users/me/Library/Caches/a", "/Users/me/Library/Caches/b", "/Users/me/repos/p/node_modules"],
            "container items listed one by one, Trash left out"
        );
    }
}
